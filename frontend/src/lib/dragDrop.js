// Отпустить строку в списке, который переставляют за ручку (TrackRows,
// TracklistEditor). После перестановки строка уже стоит на новом месте, а
// снятый сдвиг доигрывался анимацией от прежнего — строка отскакивала на
// целый шаг и ехала обратно. Поэтому: один кадр без анимаций (соседи
// встают сразу, отпущенная — там, где её отпустили), потом остаток сдвига
// анимируется в ноль. И шаг — со щелью между строками, иначе соседи
// расступались на щель меньше, и строки дёргались на неё при отпускании.

/** Шаг между строками списка: высота строки и щель (gap) родителя. */
export function rowStep(slot) {
  return slot.offsetHeight + (parseFloat(getComputedStyle(slot.parentElement).rowGap) || 0);
}

/** Сколько отпущенной строке осталось доехать: её сдвиг минус шаги, на которые она переехала. */
export const dropRest = (drag, to) => drag.dy - (to - drag.i) * drag.h;

/** Ждёт, пока кадр с новым порядком нарисован. */
export const nextPaint = () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
