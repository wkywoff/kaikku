// Размер большого названия в шапке (Hero) — по реальной ширине текста, как
// в Spotify: самый крупный, при котором название встаёт в одну строку.
// Раньше размер выбирался по числу символов, и «TALL MAN MIXTAPE» (16
// знаков) получал 54 px при пустой половине шапки.
//
//   avail — ширина колонки под название, px;
//   unit  — ширина названия в одну строку при font-size 1 px (ширина растёт
//           линейно с кеглем, межбуквенное задано в em);
//   min, max — границы кегля, px.
//
// Не влезает даже при min — остаётся min, и строка переносится. Мерить
// нечего (колонка ещё не разложена, пустое название) — тоже min: крупный
// текст, который потом сожмётся, заметнее мелкого, который вырастет.
export function fitFontSize(avail, unit, min, max) {
  if (!(avail > 0) || !(unit > 0)) return min;
  // Вниз до целого: на дробном кегле округление глифов может дать перенос.
  return Math.max(min, Math.min(max, Math.floor(avail / unit)));
}
